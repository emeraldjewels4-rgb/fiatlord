ARTIFACTS = [
    "build/mined_artifacts.json",
    "build/qdt_artifacts.json",
    "build/aud_artifacts.json",
    "build/bridge_artifacts.json",
]


def contracts():
    """Contract name -> runtime bytecode, from every artifact that has one."""
    found = {}
    for rel in ARTIFACTS:
        path = os.path.join(ROOT, rel)
        if not os.path.isfile(path):
            continue
        with open(path, encoding="utf-8") as fh:
            data = json.load(fh)
        for name, entry in data.items():
            hexdata = (entry or {}).get("deployed_bytecode") or ""
            if len(hexdata) <= 2:
                continue
            found[name] = hexdata
    return found


def addresses():
    """Contract name -> [(chain, address)], from the deployment record."""
    by_contract = {}
    path = os.path.join(ROOT, "build", "deployments.json")
    if not os.path.isfile(path):
        return by_contract
    with open(path, encoding="utf-8") as fh:
        data = json.load(fh)
    for key, entry in data.items():
        if not isinstance(entry, dict):
            continue
        name = entry.get("contract")
        address = entry.get("address")
        if not name or not address:
            continue
        # The key is the deployment slot (polygon, arbitrum_lock, polygon_escrow2);
        # the chain is its first segment, which is also what the explorer map uses.
        chain = key.split("_")[0]
        by_contract.setdefault(name, []).append({"chain": chain, "address": address})
    return by_contract


def panel():
    addr = addresses()
    rows = []
    for name in sorted(contracts()):
        hexdata = contracts()[name]
        raw = bytes.fromhex(hexdata[2:])
        rows.append({
            "name": name,
            "chains": addr.get(name, []),
            "hex": hexdata,
            "bytes": len(raw),
            "sha256": hashlib.sha256(raw).hexdigest(),
        })
    return {
        "generated": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "contracts": rows,
    }


