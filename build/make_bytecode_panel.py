def _same_page(current, fresh):
    """Compare two pages, ignoring the build time stamped into each.

    The stamp is the moment of the build, so it differs on every run by design;
    comparing it would make this check say "would change" even when every
    contract, byte and digest matches.
    """
    stamp = re.compile(r'"generated":"[^"]*"')
    return stamp.sub('"generated":""', current) == stamp.sub('"generated":""', fresh)


def render(payload):
    packed = json.dumps(payload, separators=(",", ":"), sort_keys=True)
    if "JSON\n" in packed:
        raise SystemExit("panel data would end the heredoc; refusing")
    return TEMPLATE.replace("__DATA__", packed)


def main(argv=None):
    ap = argparse.ArgumentParser(description="Build the bytecode panel page.")
    ap.add_argument("--check", action="store_true", help="report only, write nothing")
    args = ap.parse_args(argv)

    payload = panel()
    if not payload["contracts"]:
        raise SystemExit("no artifact holds any runtime bytecode; nothing to build")

    page = render(payload)
    page.encode("ascii")  # the page is ASCII by contract with .gitattributes

    if args.check:
        print(f"{len(payload['contracts'])} contracts, {sum(c['bytes'] for c in payload['contracts'])} bytes of code")
        if os.path.isfile(OUT):
            current = open(OUT, "rb").read().decode("ascii")
            print("up to date" if _same_page(current, page) else "would change")
        return 0

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "wb") as fh:
        fh.write(page.encode("ascii"))
    for contract in payload["contracts"]:
        where = ", ".join(f"{c['chain']}:{c['address']}" for c in contract["chains"]) or "no address"
        print(f"  {contract['name']:<20} {contract['bytes']:>6} bytes  {where}")
    print(f"\nwrote {OUT} ({len(page)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
